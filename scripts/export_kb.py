"""Exports what the server needs from the phone's engine to app/data/kb.json, so there is one source of truth:
scheme names, benefits, conditions (the rule labels, in plain words), documents and sources; where each document
is made; the plan step texts for every path; and the decision dates for Class 10.

    python scripts/export_kb.py

Run it after changing app/js/engine.js or app/data/paths.json. tests/e2e/test_teacher.py fails if kb.json drifts.
The teacher view and Ask OpenPath read kb.json; they never see the rule code and never decide eligibility.
"""
from __future__ import annotations

import json
import os
import socket
import subprocess
import sys
import time
from pathlib import Path

import httpx
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "data" / "kb.json"

# Runs in the app page: imports the same engine module the phone uses.
EXPORT_JS = r"""async () => {
  const E = await import('/js/engine.js');
  await E.loadData('/data/');
  const base = Object.assign(E.blankProfile(), { cls: 10, docs: { aadhaar: true, bank: true, income: true, community: true } });
  const plan = {}, decisions = {};
  E.PATHS.forEach(p => {
    // With every document held there are no document tasks: lesson, stories, practice, visit, decide.
    const t = [].concat(...E.makePlan(p, base, E.evaluateAll(base, p))).map(x => x.text);
    plan[p.id] = { lesson: t[0], stories: t[1], practice: t[2], visit: t[3], decide: t[4] };
    decisions[p.id] = E.nextDecision(p, base);
  });
  return {
    checked: E.CHECKED,
    schemes: E.SCHEMES.map(s => ({ id: s.id, name: s.name, by: s.by, when: s.when, benefit: s.benefit,
      conditions: s.checks.map(c => c.label), docs: s.docs, source: s.source })),
    docs: E.DOCS, doc_tasks: E.DOC_TASK, plan: plan, decisions: decisions
  };
}"""


def export(page) -> dict:
    data = page.evaluate(EXPORT_JS)
    return {"_note": "Generated by scripts/export_kb.py from app/js/engine.js. Do not edit by hand.", **data}


def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def main() -> None:
    port = _free_port()
    env = dict(os.environ, FAKE_SARVAM="1", DEMO_PASSCODE="000000", OPENPATH_NO_DOTENV="1", LOG_LEVEL="warning")
    proc = subprocess.Popen([sys.executable, "-m", "uvicorn", "server.main:app", "--host", "127.0.0.1", "--port", str(port)],
                            cwd=ROOT, env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    base = f"http://127.0.0.1:{port}"
    try:
        for _ in range(100):
            try:
                if httpx.get(base + "/api/health", timeout=1).status_code == 200:
                    break
            except httpx.HTTPError:
                time.sleep(0.1)
        with sync_playwright() as p:
            b = p.chromium.launch()
            page = b.new_page()
            page.goto(base + "/")
            page.wait_for_function("window.OPENPATH && window.OPENPATH_CHECKS")
            data = export(page)
            b.close()
    finally:
        proc.terminate()
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(data['schemes'])} schemes, {len(data['plan'])} paths")


if __name__ == "__main__":
    main()
